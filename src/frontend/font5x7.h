// 单行文本占用的像素宽度（含字间距）
inline int textWidth5x7(const char* s, int scale = 1, int spacing = 1) {
    const int n = s ? static_cast<int>(std::strlen(s)) : 0;
    if (n <= 0) return 0;
    return (n * 5 + (n - 1) * spacing) * scale;
}

// 直接往 ARGB 像素缓冲上画矩形（越界自动裁剪）
inline void fillRectBuf(std::uint32_t* buf, int w, int h,
                        int x, int y, int rw, int rh, std::uint32_t color) {
    if (!buf || rw <= 0 || rh <= 0) return;
    const int x0 = x < 0 ? 0 : x;
    const int y0 = y < 0 ? 0 : y;
    const int x1 = (x + rw > w) ? w : x + rw;
    const int y1 = (y + rh > h) ? h : y + rh;
    for (int j = y0; j < y1; ++j) {
        std::uint32_t* p = buf + static_cast<std::size_t>(j) * static_cast<std::size_t>(w) + x0;
        for (int i = x0; i < x1; ++i) *p++ = color;
    }
}

inline void drawText5x7(std::uint32_t* buf, int w, int h, int x, int y,
                        const char* s, std::uint32_t color, int scale = 1, int spacing = 1) {
    if (!s) return;
    int cx = x;
    for (const char* p = s; *p; ++p) {
        const fontimpl::Glyph& g = fontimpl::glyph(*p);
        for (int r = 0; r < 7; ++r)
            for (int c = 0; c < 5; ++c)
                if (g.row[r] & (1u << (4 - c)))
                    fillRectBuf(buf, w, h, cx + c * scale, y + r * scale, scale, scale, color);
        cx += (5 + spacing) * scale;
    }
}

// 居中绘制（按给定宽度居中）
inline void drawTextCenter5x7(std::uint32_t* buf, int w, int h, int cx, int y,
                              const char* s, std::uint32_t color, int scale = 1, int spacing = 1) {
    drawText5x7(buf, w, h, cx - textWidth5x7(s, scale, spacing) / 2, y, s, color, scale, spacing);
}


// font5x7.h — 内置 5x7 点阵字体（ASCII 32..95）
//
// 为什么自带字体：SDL2 本体不含任何字体渲染（SDL_ttf 是另一个独立库），
// 而键位设置界面必须把「键名」画到屏幕上，所以这里内置一张最小位图字体。
//
// 字形直接写成 7 行 × 5 列的 '0'/'1' 字符串——比十六进制表好读、好改、不容易写错。
// 只覆盖 ASCII 32..95（因为界面文案全用大写英文），小写字母会自动折叠成大写。

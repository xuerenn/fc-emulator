// 首次调用时把字符串展开成位掩码，之后直接查表
inline const Glyph& glyph(char c) {
    static Glyph table[64];
    static bool built = false;
    if (!built) {
        for (int i = 0; i < 64; ++i) {
            int r = 0, col = 0;
            std::uint8_t bits = 0;
            for (const char* p = kRows[i]; *p && r < 7; ++p) {
                if (*p == ' ') continue;
                if (*p == '1') bits |= std::uint8_t(1u << (4 - col));
                if (++col == 5) { table[i].row[r++] = bits; bits = 0; col = 0; }
            }
            while (r < 7) table[i].row[r++] = 0;
        }
        built = true;
    }
    int idx = static_cast<unsigned char>(c);
    if (idx >= 'a' && idx <= 'z') idx -= 32;           // 小写折叠成大写
    if (idx < 32 || idx > 95) idx = '?' - 32;          // 其它一律画 '?'
    return table[idx - 32];
}

